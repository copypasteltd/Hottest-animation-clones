export const SCHEMA = 'motion-catalog/2';
export const TAXONOMY = 'motion-tags/1.0';
export const RANKING = 'fresh55-heat45/1';
export const PAGE_SIZE = 24;
export const platforms = ['bilibili', 'x', 'douyin'] as const;
export const variants = ['SA02', 'BM01'] as const;
export const framings = ['half_body', 'full_body'] as const;
export const shapes = ['portrait', 'landscape', 'square'] as const;
export const scopes = ['native', 'source', 'rendition', 'configuration'] as const;
export type Platform = typeof platforms[number];
export type Variant = typeof variants[number];
export type Framing = typeof framings[number];
export type Shape = typeof shapes[number];
export type Scope = typeof scopes[number];
export type TagState = 'observed' | 'candidate';
export const reviewStates = ['approved','pending','unrecorded'] as const;
export type ReviewState = typeof reviewStates[number];
export const reviewName: Record<ReviewState,string> = {approved:'已定稿',pending:'待复核',unrecorded:'未记录验收'};
export const detailKinds = ['author','platform','media','route','configuration','review','observation','comparison','limitation'] as const;
export type DetailKind = typeof detailKinds[number];
export type IndexedDetail = {kind: DetailKind; text: string; candidate: boolean};
export const detailName: Record<DetailKind,string> = {author:'作者',platform:'平台资料',media:'媒体规格',route:'取景路线',configuration:'生成配置',review:'验收状态',observation:'观察说明',comparison:'对照说明',limitation:'证据限制'};
export const noteKind = (kind: DetailKind) => kind==='observation'||kind==='comparison'||kind==='limitation';
export type HeatState = 'available' | 'missing' | 'stale' | 'incomparable';
export type LocaleMode = 'example' | 'local'; // No release-media exporter in v1.
export type Tag = {id: string; scope: Scope; zh: string; en: string; aliases: string[]; facet: string};
export type TagRef = {id: string; state: TagState};
export type Poster = {path: string; width: number; height: number};
export type Work = {id: string; title: string; description: string; code: string | null; platform: Platform;
  listedAt: string | null; heat: number | null; heatAt: string | null; heatState: HeatState; tags: TagRef[]; detailsIndex: IndexedDetail[]};
export type Rendition = {id: string; workId: string; title: string; description: string; variant: Variant;
  framing: Framing; shape: Shape; durationMs: number; listedAt: string | null; label: string;
  poster: Poster | null; playable: boolean; tags: TagRef[]; reviewStatus: ReviewState; detailsIndex: IndexedDetail[]};
export type Catalog = {works: Work[]; renditions: Rendition[]};
export type Bundle = {version: string; value: unknown};
export type Ref = {path: string; sha256: string};
export type Meta = {schemaVersion: typeof SCHEMA; taxonomyVersion: typeof TAXONOMY; rankingVersion: typeof RANKING;
  version: string; asOf: string; mode: LocaleMode; catalog: Ref; tags: Ref; home: Ref;
  details: Record<string, Ref>};
export type Fact = {id: string; state: TagState | 'not_observed_in_samples'; note: string; times: number[];
  interval: [number, number] | null};
export type Detail = {id: string; sourceUrl: string | null; video: string | null; sourceFacts: Fact[];
  renditionFacts: Fact[]; acceptance: string; notes: string[]};
export type Query = {q: string; tag: string[]; platform: Platform[]; variant: Variant[]; frame: Framing[];
  shape: Shape[]; scope: 'all' | 'source' | 'rendition'; candidates: boolean; approvedOnly: boolean; notes: boolean;
  view: 'works' | 'renditions'; sort: 'trend' | 'latest' | 'hot'; page: number};
export const platformName: Record<Platform, string> = {bilibili: 'Bilibili', x: 'X', douyin: '抖音'};
export const variantName: Record<Variant, string> = {SA02: 'SA02 动漫', BM01: 'BM01 真人'};
export const scopeName: Record<Scope, string> = {native: '平台原始', source: '原片观察', rendition: '成片观察', configuration: '生成配置'};
export const frameName: Record<Framing, string> = {full_body: '全身', half_body: '半身'};
export const shapeName: Record<Shape, string> = {portrait: '竖屏', landscape: '横屏', square: '方屏'};
export const tagIdPattern = /^(?:native|source|rendition|configuration):[a-z0-9][a-z0-9._-]{0,95}$/;
export const idPattern = /^(?:work|video)-[a-z0-9][a-z0-9-]{0,62}$/;
export const emptyQuery = (): Query => ({q: '', tag: [], platform: [], variant: [], frame: [], shape: [], scope: 'all', candidates: false, approvedOnly: false, notes: false, view: 'renditions', sort: 'trend', page: 1});
export const cmpText = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
export const utc = (v: string | null): number | null => {
  if (v === null || !/^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{1,3})?Z$/.test(v)) return null;
  const date = Date.parse(v);
  return Number.isFinite(date) && new Date(date).toISOString().slice(0, 19) === v.slice(0, 19) ? date : null;
};
